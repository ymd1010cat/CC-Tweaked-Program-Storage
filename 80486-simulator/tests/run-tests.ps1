# 80486-simulator/tests/run-tests.ps1 -- run the whole simulator test suite.
#
#   pwsh -NoProfile -File 80486-simulator\tests\run-tests.ps1
#   pwsh -NoProfile -File 80486-simulator\tests\run-tests.ps1 -Keep   # keep staging
#
# Stages a throw-away CraftOS-PC data directory at 80486-simulator/.tests:
#
#     .tests/computer/20/startup.lua                    generated runner shim
#     .tests/computer/20/{memory,disk,cpu,vga,bios}.lua  modules (require path)
#     .tests/computer/20/runner.lua                      machine entry point
#     .tests/computer/20/80486-simulator/*.lua           loadfile fallback path
#     .tests/computer/20/tests/*.lua                     the suites
#
# and boots it headless.  The shim runs every suite, captures each suite's
# "N passed, M skipped, K failed" summary and writes a self-contained report
# to /suite-report.txt.  The CraftOS console redraws partial lines, so the
# report file is authoritative.  A run is green only when every suite loaded,
# the aggregated failure count is zero AND the aggregated skip count is zero:
# skipped checks never count as passes.
#
# The staging directory is deleted again unless -Keep is passed.
param(
    [int]$TimeoutSec = 240,
    [string]$Exe = "C:\Program Files\CraftOS-PC\CraftOS-PC_console.exe",
    [switch]$Keep
)

$ErrorActionPreference = "Stop"

$here    = Split-Path -Parent $MyInvocation.MyCommand.Path   # 80486-simulator/tests
$simRoot = Split-Path -Parent $here                          # 80486-simulator
$stage   = Join-Path $simRoot ".tests"
$comp    = Join-Path $stage "computer\20"
$stdout  = Join-Path $stage "stdout.txt"
$stderr  = Join-Path $stage "stderr.txt"

if (-not (Test-Path $Exe)) {
    Write-Output "TEST_ERROR missing emulator: $Exe"
    exit 2
}

$modules = @("memory.lua", "disk.lua", "cpu.lua", "vga.lua", "bios.lua",
             "runner.lua")
$tests   = @("memory_test.lua", "disk_test.lua", "cpu_test.lua",
             "vga_test.lua", "bios_test.lua", "bios_services_test.lua",
             "runner_test.lua", "test_integration.lua")

foreach ($module in $modules) {
    $path = Join-Path $simRoot $module
    if (-not (Test-Path $path)) {
        Write-Output "TEST_ERROR missing source file: $path"
        exit 2
    }
}
foreach ($name in $tests) {
    $path = Join-Path $simRoot ("tests\" + $name)
    if (-not (Test-Path $path)) {
        Write-Output "TEST_ERROR missing test file: $path"
        exit 2
    }
}

Remove-Item $stage -Recurse -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force -Path $comp | Out-Null
New-Item -ItemType Directory -Force -Path (Join-Path $comp "tests") | Out-Null
New-Item -ItemType Directory -Force -Path (Join-Path $comp "80486-simulator") | Out-Null

# The suites load modules with require() or with a loadfile() fallback, so
# stage each module under both spellings.
foreach ($module in $modules) {
    Copy-Item (Join-Path $simRoot $module) (Join-Path $comp $module) -Force
    Copy-Item (Join-Path $simRoot $module) (Join-Path $comp "80486-simulator\$module") -Force
}
foreach ($name in $tests) {
    Copy-Item (Join-Path $simRoot ("tests\" + $name)) (Join-Path $comp ("tests\" + $name)) -Force
}

# CraftOS runs /startup.lua at boot.  The shim keeps crashes visible as
# normal SUITE_FAIL lines and aggregates the per-suite counters itself.
$shim = @(
    "-- generated by 80486-simulator/tests/run-tests.ps1",
    "local suites = {",
    "    {`"memory`", `"/tests/memory_test.lua`"},",
    "    {`"disk`", `"/tests/disk_test.lua`"},",
    "    {`"cpu`", `"/tests/cpu_test.lua`"},",
    "    {`"vga`", `"/tests/vga_test.lua`"},",
    "    {`"bios`", `"/tests/bios_test.lua`"},",
    "    {`"bios_services`", `"/tests/bios_services_test.lua`"},",
    "    {`"runner`", `"/tests/runner_test.lua`"},",
    "    {`"integration`", `"/tests/test_integration.lua`"},",
    "}",
    "local captured = {}",
    "local real_print = print",
    "_G.print = function(...)",
    "    local parts = {}",
    "    for i = 1, select(`"#`", ...) do",
    "        parts[#parts + 1] = tostring((select(i, ...)))",
    "    end",
    "    local line = table.concat(parts, `" `")",
    "    captured[#captured + 1] = line",
    "    real_print(...)",
    "end",
    "local report = {}",
    "local all_ok = true",
    "for i = 1, #suites do",
    "    local name, path = suites[i][1], suites[i][2]",
    "    local ok, err = pcall(dofile, path)",
    "    if ok then",
    "        report[#report + 1] = `"SUITE `" .. name .. `" ok`"",
    "    else",
    "        all_ok = false",
    "        local text = tostring(err):gsub(`"%s+`", `" `")",
    "        report[#report + 1] = `"SUITE `" .. name .. `" FAIL `" .. text",
    "    end",
    "end",
    "_G.print = real_print",
    "local sums = { pass = 0, skip = 0, fail = 0 }",
    "for i = 1, #captured do",
    "    local line = captured[i]",
    "    local p, s, f = line:match(`"(%d+) passed, (%d+) skipped, (%d+) failed`")",
    "    if p ~= nil then",
    "        report[#report + 1] = `"SUMMARY `" .. line",
    "        sums.pass = sums.pass + tonumber(p)",
    "        sums.skip = sums.skip + tonumber(s)",
    "        sums.fail = sums.fail + tonumber(f)",
    "    elseif line:match(`"^SKIP`") then",
    "        report[#report + 1] = `"SKIPLINE `" .. line",
    "    end",
    "end",
    "report[#report + 1] = string.format(`"COUNTS pass=%d skip=%d fail=%d`",",
    "    sums.pass, sums.skip, sums.fail)",
    "if all_ok and sums.fail == 0 then",
    "    report[#report + 1] = `"SUITE_PASS`"",
    "else",
    "    report[#report + 1] = `"SUITE_FAIL`"",
    "end",
    "local handle = fs.open(`"/suite-report.txt`", `"wb`")",
    "if handle then",
    "    handle.write(table.concat(report, `"\n`") .. `"\n`")",
    "    handle.close()",
    "end",
    "print(`"SUITE_DONE`")",
    "pcall(os.shutdown)"
)
Set-Content -Path (Join-Path $comp "startup.lua") -Value $shim -Encoding ascii

$reportPath = Join-Path $comp "suite-report.txt"
$proc = Start-Process -FilePath $Exe -ArgumentList @("-d", "`"$stage`"", "--headless", "--id", "20") `
    -RedirectStandardOutput $stdout -RedirectStandardError $stderr -PassThru -NoNewWindow

$deadline = (Get-Date).AddSeconds($TimeoutSec)
while ((Get-Date) -lt $deadline) {
    Start-Sleep -Milliseconds 250
    if ($proc.HasExited) { break }
    if (Test-Path $reportPath) {
        $probe = Get-Content $reportPath -Raw
        if ($probe -match "SUITE_PASS|SUITE_FAIL") { break }
    }
}
Start-Sleep -Milliseconds 300
if (-not $proc.HasExited) { $proc.Kill() }
Start-Sleep -Milliseconds 200

$reportLines = @()
if (Test-Path $reportPath) {
    $reportLines = @((Get-Content $reportPath -Raw) -replace "`r", "" -split "`n" |
        Where-Object { $_ -ne "" })
}

foreach ($line in $reportLines) {
    Write-Output $line
}

$counts = $null
foreach ($line in $reportLines) {
    if ($line -match "^COUNTS pass=(\d+) skip=(\d+) fail=(\d+)") {
        $counts = @{
            pass = [int]$Matches[1]
            skip = [int]$Matches[2]
            fail = [int]$Matches[3]
        }
    }
}

$suiteOk = 0
$suiteCount = 0
foreach ($line in $reportLines) {
    if ($line -match "^SUITE ") {
        $suiteCount++
        if ($line -match " ok$") { $suiteOk++ }
    }
}

$passed = $false
if (($reportLines -contains "SUITE_PASS") -and $counts -ne $null) {
    $passed = ($counts.fail -eq 0) -and ($counts.skip -eq 0) `
        -and ($suiteOk -eq $suiteCount) -and ($suiteCount -eq 8)
}

if (-not $passed) {
    if (Test-Path $stdout) {
        Write-Output "--- stdout ---"
        Get-Content $stdout -Raw
    }
    if (Test-Path $stderr) {
        $errText = Get-Content $stderr -Raw
        if ($errText) {
            Write-Output "--- stderr ---"
            Write-Output $errText
        }
    }
}

if ($Keep) {
    Write-Output "TEST_STAGING $stage"
} else {
    Remove-Item $stage -Recurse -Force -ErrorAction SilentlyContinue
}

if ($passed) {
    Write-Output "TEST_PASS"
    exit 0
}
Write-Output "TEST_FAIL"
exit 1
