"""A 6x9 public-domain ASCII/Latin-1 bitmap font for term_font.png.

SOURCE
    From `6x9.bdf`, part of Markus Kuhn's Unicode versions of the X11
    "misc-fixed" fonts (the "ucs-fonts" package):

        http://www.cl.cam.ac.uk/~mgk25/ucs-fonts.html
        http://www.cl.cam.ac.uk/~mgk25/download/ucs-fonts.tar.gz
        file 6x9.bdf, "$Id: 6x9.bdf,v 1.28 2006-01-05 ... $"

    The BDF's own COPYRIGHT property says, verbatim:

        "Public domain font.  Share and enjoy."

    The package's AUTHORS file records that the identity of the designers of
    the original ASCII repertoire and its Latin-1 extension "appears to have
    been lost in history" (probably MIT Project Athena or DEC, early-to-mid
    1980s).  The package README states that contributors agree the resulting
    font files "will remain in the public domain for everyone's free use".

    This table is therefore public domain: it may be copied, modified and
    redistributed with no conditions and no attribution requirement.  The
    attribution above is given as a courtesy, not as an obligation.

WHY 6x9
    CC:Tweaked's FixedWidthFontRenderer declares FONT_WIDTH = 6 and
    FONT_HEIGHT = 9, so the glyph box of term_font.png is exactly 6x9 pixels.
    This table is that size: it drops into the box at (0, 0) with no scaling
    and no clipping, and it keeps the same internal margins as the X11 font
    (capitals occupy pixel rows 1..6, descenders reach row 8, and every
    printable character except "%" leaves column 5 blank for spacing).

    The alternatives were rejected on geometry, not taste.  An 8x8 font such
    as Daniel Hepper's public-domain font8x8_basic does not fit at all: its
    letters are 7-8 pixels wide and clipping the right column destroys B, D,
    E, F, ...  A 5x7 font fits, but wastes two of the nine rows and -- because
    a capital letter already fills its six rows -- cannot draw the accents of
    Latin-1 capitals such as U+00C9.  The 6x9 variant of the same public-domain
    family fits the cell exactly and has room for accents and descenders.

WHAT IS STORED, AND THE BIT ORDER
    GLYPHS maps a codepoint to its nine rows, top row first.  Each row is a
    byte in which bit 7 is the leftmost of the six pixel columns, exactly as
    in the BDF source (BDF pads a 6-pixel row to a byte on the right).

    The two ranges are the two parts of term_font.png that carry text:

        U+0020..U+007E  -> bytes   0..127   (ASCII)
        U+00C0..U+00FF  -> bytes 192..255   (Latin-1 letters and symbols)

    Bytes 128..191 are not glyphs at all: they are the 2x3 sub-cell blocks
    that unixshell/lib/cc_chinese.lua writes with term.blit, and
    make_pack.py draws those itself.
"""

