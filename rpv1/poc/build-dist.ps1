# ---- manifest --------------------------------------------------------------
function Get-Crc32 {
    param([byte[]]$Bytes)
    # decimal literals + [uint64] casts: PowerShell's 0xFFFFFFFF literal is a
    # negative int32, so [uint64]0xFFFFFFFF throws
    $M32 = [uint64]4294967295
    $POLY = [uint64]3988292384          # 0xEDB88320
    $table = New-Object uint64[] 256
    for ($i = 0; $i -lt 256; $i++) {
        $c = [uint64]$i
        for ($k = 0; $k -lt 8; $k++) {
            if ($c -band 1) { $c = ($POLY -bxor ($c -shr 1)) -band $M32 } else { $c = ($c -shr 1) -band $M32 }
        }
        $table[$i] = $c
    }
    $crc = $M32
    foreach ($b in $Bytes) {
        $idx = [int](($crc -bxor [uint64]$b) -band [uint64]255)
        $crc = ($table[$idx] -bxor ($crc -shr 8)) -band $M32
    }
    $crc = ($crc -bxor $M32) -band $M32
    return [uint32]$crc
}

$sha = [System.Security.Cryptography.SHA256]::Create()
$lines = New-Object System.Collections.Generic.List[string]
$lines.Add("# RPV1 library $Version - sha256 / crc32 / size / path")
$lines.Add("# generated by poc/build-dist.ps1 (do not edit)")
foreach ($f in (Get-ChildItem $dist -Recurse -File | Where-Object { $_.Name -ne "MANIFEST.txt" -and $_.Extension -ne ".zip" } | Sort-Object FullName)) {
    $rel = $f.FullName.Substring($dist.Length + 1).Replace("\", "/")
    $bytes = [System.IO.File]::ReadAllBytes($f.FullName)
    $h = ($sha.ComputeHash($bytes) | ForEach-Object { $_.ToString("x2") }) -join ""
    $crc = Get-Crc32 $bytes
    $lines.Add(("{0} {1:x8} {2} {3}" -f $h, $crc, $bytes.Length, $rel))
}
Write-Ascii (Join-Path $dist "MANIFEST.txt") (($lines -join "`n") + "`n")

# ---- zip -------------------------------------------------------------------
