# Build the RPV1 deployment package into dist\ (internal use; nothing is published).
#
#   pwsh -File poc\build-dist.ps1                 # build + manifest + zip
#   pwsh -File poc\build-dist.ps1 -Version 1.1.0
#
# Produces (all ASCII, no BOM):
#   dist\rpv.lua                library entry point (folder layout)
#   dist\rpv\*.lua              the modules
#   dist\compat\rednet.lua      rednet compatibility shim
#   dist\examples\*.lua         external-program examples + library self-check
#   dist\rpv-bundle.lua         SINGLE-FILE build (drop one file on a computer)
#   dist\install.lua            on-computer installer (dir/floppy or http source)
#   dist\API.md dist\README.md
#   dist\LICENSE                MIT license (copied from the repository root)
#   dist\MANIFEST.txt           sha256 + crc32 + size for every shipped file
#   dist\rpv-<version>.zip      the whole thing zipped
param(
    [string]$Version = "1.0.0",
    [string]$Root = $env:RPV_ROOT
)

$root = $Root
if (-not $root) { $root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path) }
$env:RPV_ROOT = $root
$poc = Join-Path $root "poc"
$dist = Join-Path $root "dist"
$rpvdir = Join-Path $poc "rpv"
$examples = Join-Path $poc "examples"
$compat = Join-Path $poc "compat"

$MODULES = @("crypto", "util", "ip", "route", "arp", "link", "icmp", "udp", "conn", "fabric", "wan", "services", "dv", "nat", "mcast", "qos", "wansec", "compat", "topo")

function Write-Ascii {
    param([string]$Path, [string]$Text)
    $dir = Split-Path -Parent $Path
    if ($dir) { New-Item -ItemType Directory -Force -Path $dir | Out-Null }
    [System.IO.File]::WriteAllText($Path, $Text, (New-Object System.Text.ASCIIEncoding))
}

# ---- clean -----------------------------------------------------------------
if (Test-Path $dist) { Remove-Item -Recurse -Force $dist }
foreach ($sub in @("rpv", "compat", "examples")) { New-Item -ItemType Directory -Force -Path (Join-Path $dist $sub) | Out-Null }

# ---- folder layout ---------------------------------------------------------
Copy-Item (Join-Path $poc "rpv.lua") (Join-Path $dist "rpv.lua") -Force
foreach ($m in $MODULES + @("node")) {
    Copy-Item (Join-Path $rpvdir "$m.lua") (Join-Path $dist "rpv\$m.lua") -Force
}
Copy-Item (Join-Path $compat "rednet.lua") (Join-Path $dist "compat\rednet.lua") -Force
Copy-Item (Join-Path $examples "*.lua") (Join-Path $dist "examples") -Force
Copy-Item (Join-Path $rpvdir "API.md") (Join-Path $dist "API.md") -Force
Copy-Item (Join-Path $poc "dist-src\install.lua") (Join-Path $dist "install.lua") -Force

# ---- single-file bundle ----------------------------------------------------
function Embed-Lua {
    param([string]$Path, [string]$Name)
    $src = [System.IO.File]::ReadAllText($Path)
    if ($src -match "\]\]==\]") { throw "cannot embed ${Path}: contains the long-bracket terminator" }
    if ($src.Contains("`r")) { $src = $src.Replace("`r`n", "`n") }
    return "[==[`n$src]==]"
}

