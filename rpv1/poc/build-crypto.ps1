# Regenerate poc/rpv/crypto.lua (library module form) from the implementation in
# poc/security/crypto.lua, which stays the single source of truth.
#
#   pwsh -File poc\build-crypto.ps1
#
# The generated module is loaded by rpv.lua, so library users get M.sha256 /
# M.hmac_sha256 / M.hkdf_sha256 / M.pbkdf2_sha256 / M.chacha20_xor / M.hex /
# M.unhex / M.seed_entropy without carrying a second crypto file. The security
# prototypes and the ftp apps keep doing `local crypto = dofile("crypto.lua")`.
param([string]$Root = $env:RPV_ROOT)

$root = $Root
if (-not $root) { $root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path) }
$srcPath = Join-Path $root "poc\security\crypto.lua"
$dstPath = Join-Path $root "poc\rpv\crypto.lua"

$src = [System.IO.File]::ReadAllText($srcPath)
if ($src.Length -lt 5000) { throw "source looks truncated ($($src.Length) bytes): $srcPath" }

# 1. drop the original header comment block
$src = [regex]::Replace($src, '^--\[\[-.*?\]\]\s*', '', [System.Text.RegularExpressions.RegexOptions]::Singleline)
# 2. drop the local table, keep the rest
$src = $src.Replace("local crypto = {}", '')
# 3. cut the trailing "return crypto"
$idx = $src.LastIndexOf("return crypto")
if ($idx -lt 0) { throw "cannot find the trailing 'return crypto' in $srcPath" }
$src = $src.Substring(0, $idx)
# 4. qualify everything with the shared library table
$src = [regex]::Replace($src, '\bcrypto\.', 'M.')
$src = $src.TrimEnd() + "`n"

$header = @"
--[[- rpv/crypto.lua - pure-Lua crypto primitives (library module form).

GENERATED by poc/build-crypto.ps1 from poc/security/crypto.lua, which is the
single source of truth (edit that file, then re-run the build; the script fails
loudly if the source looks truncated).

Loaded by rpv.lua, so every library user gets M.sha256 / M.hmac_sha256 /
M.hkdf_sha256 / M.pbkdf2_sha256 / M.chacha20_xor / M.seed_entropy / M.hex /
M.unhex. The security prototypes and the ftp apps keep calling
`local crypto = dofile("crypto.lua")` (the harnesses copy both files).

No AES and no public-key crypto on purpose: CC has no big-integer library and
pure-Lua AES is slow and easy to get wrong. Integrity is encrypt-then-MAC with
HMAC-SHA256, which needs one primitive and is verifiable with RFC test vectors.
]]
local M = ...
"@

$out = $header + $src + "`nreturn M`n"
$refs = ([regex]::Matches($out, 'M\.')).Count
if ($out.Length -lt 5000 -or $refs -lt 30) {
    throw "generated module looks wrong ($($out.Length) bytes, $refs M. refs) - refusing to write"
}
[System.IO.File]::WriteAllText($dstPath, $out, (New-Object System.Text.ASCIIEncoding))
"generated poc/rpv/crypto.lua: $($out.Length) bytes, $refs M. refs"
