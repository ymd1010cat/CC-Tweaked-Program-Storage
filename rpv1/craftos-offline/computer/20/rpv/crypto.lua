local H0 = { 0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19 }

local function sha256_compress(h, block)
    local w = {}
    for i = 0, 15 do
        local o = i * 4
        w[i] = byte(block, o + 1) * 0x1000000 + byte(block, o + 2) * 0x10000 + byte(block, o + 3) * 0x100 + byte(block, o + 4)
    end
    for i = 16, 63 do
        local x, y = w[i - 15], w[i - 2]
        local s0 = bxor(rotr(x, 7), rotr(x, 18), rshift(x, 3))
        local s1 = bxor(rotr(y, 17), rotr(y, 19), rshift(y, 10))
        w[i] = add32(w[i - 16], s0, w[i - 7], s1)
    end
    local a, b, c, d, e, f, g, hh = h[1], h[2], h[3], h[4], h[5], h[6], h[7], h[8]
    for i = 0, 63 do
        local S1 = bxor(rotr(e, 6), rotr(e, 11), rotr(e, 25))
        local ch = bxor(band(e, f), band(bnot(e), g))
        local t1 = add32(hh, S1, ch, K[i + 1], w[i])
        local S0 = bxor(rotr(a, 2), rotr(a, 13), rotr(a, 22))
        local maj = bxor(band(a, b), band(a, c), band(b, c))
        local t2 = add32(S0, maj)
        hh, g, f, e, d, c, b, a = g, f, e, add32(d, t1), c, b, a, add32(t1, t2)
    end
    h[1], h[2], h[3], h[4] = add32(h[1], a), add32(h[2], b), add32(h[3], c), add32(h[4], d)
    h[5], h[6], h[7], h[8] = add32(h[5], e), add32(h[6], f), add32(h[7], g), add32(h[8], hh)
end

function M.sha256(msg)
    msg = tostring(msg)
    local h = { H0[1], H0[2], H0[3], H0[4], H0[5], H0[6], H0[7], H0[8] }
    local len = #msg
    local bits = len * 8
    local padded = msg .. "\128" .. rep("\0", (55 - len) % 64)
        .. u32be(floor(bits / 4294967296)) .. u32be(bits % 4294967296)
    for i = 1, #padded, 64 do sha256_compress(h, sub(padded, i, i + 63)) end
    local out = {}
    for i = 1, 8 do out[i] = u32be(h[i]) end
    return concat(out)
end

-- ===== HMAC-SHA256 =====
local HMAC_BLOCK = 64
function M.hmac_sha256(key, msg)
    if #key > HMAC_BLOCK then key = M.sha256(key) end
    key = key .. rep("\0", HMAC_BLOCK - #key)
    local ipad, opad = {}, {}
    for i = 1, HMAC_BLOCK do
        local k = byte(key, i)
        ipad[i] = char(bxor(k, 0x36))
        opad[i] = char(bxor(k, 0x5c))
    end
    return M.sha256(concat(opad) .. M.sha256(concat(ipad) .. msg))
end

-- ===== HKDF-SHA256 (RFC 5869) =====
function M.hkdf_sha256(ikm, salt, info, length)
    salt = (salt == nil or salt == "") and rep("\0", 32) or salt
    info = info or ""
    local prk = M.hmac_sha256(salt, ikm)
    local out, t, n = {}, "", 0
    while #concat(out) < length do
        n = n + 1
        t = M.hmac_sha256(prk, t .. info .. char(n))
        out[#out + 1] = t
    end
    return sub(concat(out), 1, length)
end

-- ===== PBKDF2-HMAC-SHA256 (RFC 8018) =====
-- yield_every: call os.sleep(0) every N iterations so CC's "too long without
-- yielding" watchdog does not kill the computer during a handshake.
function M.pbkdf2_sha256(pass, salt, iters, dklen, yield_every)
    iters = iters or 4096
    dklen = dklen or 32
    local out = {}
    for i = 1, math.ceil(dklen / 32) do
        local u = M.hmac_sha256(pass, salt .. u32be(i))
        local t = u
        for n = 2, iters do
            u = M.hmac_sha256(pass, u)
            t = M.xor(t, u)
            if yield_every and n % yield_every == 0 and os.sleep then os.sleep(0) end
        end
        out[i] = t
    end
    return sub(concat(out), 1, dklen)
end

-- ===== ChaCha20 (RFC 8439) =====
local CHACHA_CONST = { 0x61707865, 0x3320646e, 0x79622d32, 0x6b206574 }

local function chacha_qr(x, a, b, c, d)
    x[a] = add32(x[a], x[b]); x[d] = rotl(bxor(x[d], x[a]), 16)
    x[c] = add32(x[c], x[d]); x[b] = rotl(bxor(x[b], x[c]), 12)
    x[a] = add32(x[a], x[b]); x[d] = rotl(bxor(x[d], x[a]), 8)
    x[c] = add32(x[c], x[d]); x[b] = rotl(bxor(x[b], x[c]), 7)
end

-- counter: number (low 32 bits are enough for our frames)
-- state (RFC 8439, 16 words): constants(4) | key(8) | counter(1) | nonce(3)
function M.chacha20_block(key, nonce, counter)
    assert(#key == 32, "chacha20: key must be 32 bytes, got " .. tostring(#key))
    assert(#nonce == 12, "chacha20: nonce must be 12 bytes, got " .. tostring(#nonce))
    local st = {
        CHACHA_CONST[1], CHACHA_CONST[2], CHACHA_CONST[3], CHACHA_CONST[4],
        r32le(key, 1), r32le(key, 5), r32le(key, 9), r32le(key, 13),
        r32le(key, 17), r32le(key, 21), r32le(key, 25), r32le(key, 29),
        floor(counter) % 4294967296,
        r32le(nonce, 1), r32le(nonce, 5), r32le(nonce, 9),
    }
    local x = {}
    for i = 1, 16 do x[i] = st[i] end
    for _ = 1, 10 do
        chacha_qr(x, 1, 5, 9, 13); chacha_qr(x, 2, 6, 10, 14); chacha_qr(x, 3, 7, 11, 15); chacha_qr(x, 4, 8, 12, 16)
        chacha_qr(x, 1, 6, 11, 16); chacha_qr(x, 2, 7, 12, 13); chacha_qr(x, 3, 8, 9, 14); chacha_qr(x, 4, 5, 10, 15)
    end
    local out = {}
    for i = 1, 16 do out[i] = u32le(add32(x[i], st[i])) end
    return concat(out)
end

function M.chacha20_xor(key, nonce, counter, data)
    local out, blocks = {}, {}
    local n = 0
    for i = 1, #data, 64 do
        n = n + 1
        local ks = M.chacha20_block(key, nonce, counter + n - 1)
        local chunk = sub(data, i, i + 63)
        blocks[n] = M.xor(chunk, sub(ks, 1, #chunk))
    end
    return concat(blocks)
end

-- ===== DRBG (deterministic random bit generator) =====
-- CC has no OS entropy: the pool is seeded from os.epoch/os.clock/computer id
-- and can be strengthened by add_entropy (e.g. operator keypresses) or by an
-- offline-generated seed file installed with the node configuration.
local pool
function M.seed_entropy()
    local parts = {
        tostring(os.epoch and os.epoch("utc") or os.time()),
        tostring(os.clock()),
        tostring(os.getComputerID and os.getComputerID() or 0),
        tostring(os.getComputerLabel and os.getComputerLabel() or ""),
    }
    -- timing jitter
    for i = 1, 16 do
        local t0 = os.clock()
        local acc = 0
        for j = 1, 50 do acc = acc + j end
        parts[#parts + 1] = format("%.9f", os.clock() - t0)
    end
    pool = M.sha256(table.concat(parts, "|"))
    return pool
end

function M.add_entropy(s)
    pool = M.sha256((pool or "") .. tostring(s))
    return pool
end

function M.load_seed_file(path)
    if fs and fs.exists and fs.exists(path) then
        local f = fs.open(path, "rb")
        local data = f.readAll()
        f.close()
        M.add_entropy(data)
        return true
    end
    return false
end

function M.random_bytes(n)
    if not pool then M.seed_entropy() end
    local out = {}
    local ctr = 0
    while #concat(out) < n do
        ctr = ctr + 1
        pool = M.sha256(pool .. tostring(os.clock()) .. char(ctr % 256))
        out[#out + 1] = pool
    end
    return sub(concat(out), 1, n)
end

function M.random_u32()
    return r32be(M.random_bytes(4), 1)
end

-- ===== self test (known-answer tests) =====
function M.selftest()
    local r = {}
    local function check(name, got, want)
        r[#r + 1] = { name = name, ok = got == want, got = got, want = want }
    end
    check("sha256('')", M.hex(M.sha256("")),
        "e3b0c44298fc1c149afbf4c8996fb92427ae41e4649b934ca495991b7852b855")
    check("sha256('abc')", M.hex(M.sha256("abc")),
        "ba7816bf8f01cfea414140de5dae2223b00361a396177a9cb410ff61f20015ad")
    check("sha256(56-byte)", M.hex(M.sha256("abcdbcdecdefdefgefghfghighijhijkijkljklmklmnlmnomnopnopq")),
        "248d6a61d20638b8e5c026930c3e6039a33ce45964ff2167f6ecedd419db06c1")
    check("hmac rfc4231#1", M.hex(M.hmac_sha256(rep("\11", 20), "Hi There")),
        "b0344c61d8db38535ca8afceaf0bf12b881dc200c9833da726e9376c2e32cff7")
    check("hmac rfc4231#4", M.hex(M.hmac_sha256(M.unhex("0102030405060708090a0b0c0d0e0f10111213141516171819"), rep("\205", 50))),
        "82558a389a443c0ea4cc819899f2083a85f0faa3e578f8077a2e3ff46729665b")
    check("pbkdf2 sha256 (P=password,S=salt,c=1)", M.hex(M.pbkdf2_sha256("password", "salt", 1, 32)),
        "120fb6cffcf8b32c43e7225256c4f837a86548c92ccc35480805987cb70be17b")
    check("hkdf rfc5869#1", M.hex(M.hkdf_sha256(
        rep("\11", 22), M.unhex("000102030405060708090a0b0c"), M.unhex("f0f1f2f3f4f5f6f7f8f9"), 42)),
        "3cb25f25faacd57a90434f64d0362f2a2d2d0a90cf1a5a4c5db02d56ecc4c5bf34007208d5b887185865")
    check("chacha20 rfc8439 block", M.hex(M.chacha20_block(
        M.unhex("000102030405060708090a0b0c0d0e0f101112131415161718191a1b1c1d1e1f"),
        M.unhex("000000090000004a00000000"), 1)),
        "10f1e7e4d13b5915500fdd1fa32071c4c7d1f4c733c068030422aa9ac3d46c4ed2826446079faa0914c2d705d98b02a2b5129cd1de164eb9cbd083e8a2503c4e")
    -- round trip
    local key = M.random_bytes(32)
    local nonce = M.random_bytes(12)
    local msg = "rpv secure frame payload"
    check("chacha20 roundtrip", M.chacha20_xor(key, nonce, 1, M.chacha20_xor(key, nonce, 1, msg)), msg)
    return r
end

