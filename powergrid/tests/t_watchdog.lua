-- t_watchdog.lua - pure state machine tests for watchdog.lua.
--
-- Everything here drives M.sample with an injected clock (plain numbers), so
-- the hysteresis rules are checked without sleeping, without redstone and
-- without touching the filesystem.

local H = ...

local W = H.watchdog

local function newW(opts)
    return W.new(opts)
end

-- Defaults -------------------------------------------------------------------

H.group("watchdog-defaults")
local w = newW({})
H.num(w.cfg.low, 2, "default low is 2")
H.num(w.cfg.high, 10, "default high is 10")
H.num(w.cfg.window, 300, "default window is 300 s")
H.num(w.cfg.poll, 10, "default poll is 10 s")
H.eq(w.cfg.alarm_side, "left", "default alarm side is left")
H.eq(w.cfg.input_side, "back", "default input side is back")
H.eq(w.cfg.enabled, true, "watchdog enabled by default")
H.eq(w.state, "init", "state starts at init")
H.eq(w.alarm, false, "no alarm at start")
H.eq(w.problem_count, 0, "no config problems for empty options")
local s, text = W.status(w)
H.isType(s, "table", "status returns a table")
H.isType(text, "string", "status returns a summary string")
H.eq(s.state, "init", "status state init")
H.eq(s.enabled, true, "status enabled")
H.contains(text, "WATCHDOG state=init", "summary carries the state")
H.contains(text, "alarm=0", "summary carries the alarm flag")
H.contains(text, "low=2 high=10 window=300", "summary carries the thresholds")
H.contains(text, "checks=0 alarms=0 recoveries=0", "summary carries the counters")
H.lacks(text, "nil", "summary never leaks nil")

-- Window / one shot ----------------------------------------------------------

H.group("watchdog-window")
local wa = newW({ low = 2, high = 10, window = 300 })
H.eq(W.sample(wa, 1, 0), "none", "first low sample is not an alarm")
H.eq(wa.state, "low", "a low sample starts the streak")
H.eq(wa.zone, "low", "zone is low")
H.num(wa.low_since, 0, "streak starts at t=0")
H.eq(W.sample(wa, 1, 100), "none", "100 s below low is not an alarm")
H.num(wa.low_since, 0, "streak start is not moved")
H.eq(wa.alarms, 0, "no alarm yet")
H.eq(W.sample(wa, 1, 299), "none", "299 s below low is not an alarm")
H.eq(wa.alarms, 0, "still no alarm")
local ev, info = W.sample(wa, 1, 300)
H.eq(ev, "alarm", "300 s below low raises the alarm")
H.eq(wa.alarm, true, "alarm latched")
H.eq(wa.alarms, 1, "alarm counted once")
H.eq(wa.state, "alarm", "state is alarm")
H.eq(wa.zone, "low", "zone stays low")
H.num(info.sustained, 300, "sustained time reported")
H.num(wa.alarm_at, 300, "alarm timestamp recorded")

H.group("watchdog-one-shot")
H.eq(W.sample(wa, 0, 400), "none", "going lower does not repeat the alarm")
H.eq(wa.alarms, 1, "alarm counter stays at one")
H.eq(W.sample(wa, 1, 900), "none", "still inside the same excursion")
H.eq(wa.alarms, 1, "one alarm per excursion")
H.eq(wa.recoveries, 0, "no recovery yet")

-- Recovery -------------------------------------------------------------------

H.group("watchdog-clear")
local wc = newW({ window = 60 })
W.sample(wc, 1, 0)
H.eq(W.sample(wc, 1, 60), "alarm", "short window alarms")
local cev, cinfo = W.sample(wc, 10, 120)
H.eq(cev, "clear", "reaching high clears the alarm")
H.eq(wc.alarm, false, "alarm cleared")
H.eq(wc.state, "ok", "state back to ok")
H.eq(wc.zone, "healthy", "zone healthy")
H.eq(wc.recoveries, 1, "recovery counted")
H.eq(wc.low_since, nil, "streak cleared")
H.num(cinfo.held, 60, "alarm hold time reported")
H.num(wc.last_clear_at, 120, "clear timestamp recorded")
H.num(select(1, W.status(wc)).low_for, 0, "low_for is zero after recovery")
H.eq(W.sample(wc, 15, 130), "none", "healthy samples are quiet")
H.eq(W.sample(wc, 1, 200), "none", "a new excursion starts again")
H.num(wc.low_since, 200, "new streak start")
H.eq(W.sample(wc, 1, 260), "alarm", "second excursion alarms again")
H.eq(wc.alarms, 2, "second alarm counted")

-- Deadband (hysteresis) ------------------------------------------------------

H.group("watchdog-deadband")
local wd = newW({ low = 2, high = 10, window = 300 })
H.eq(W.sample(wd, 5, 0), "none", "deadband sample is quiet")
H.eq(wd.zone, "deadband", "zone deadband")
H.eq(wd.state, "init", "deadband does not change the latched state")
H.eq(wd.alarm, false, "deadband never alarms by itself")
H.eq(wd.low_since, nil, "deadband does not start a streak")
H.eq(W.sample(wd, 9, 50), "none", "upper deadband is quiet too")
H.eq(wd.state, "init", "still no state change")
H.eq(W.sample(wd, 1, 100), "none", "dip below low starts the streak")
H.num(wd.low_since, 100, "streak starts at 100")
H.eq(W.sample(wd, 5, 200), "none", "deadband sample keeps the streak")
H.num(wd.low_since, 100, "deadband does not reset the streak")
H.eq(wd.state, "low", "deadband does not clear the pending state")
H.eq(wd.alarm, false, "no alarm from a deadband sample")
H.eq(W.sample(wd, 5, 400), "none", "deadband never raises the alarm")
H.eq(wd.alarm, false, "still no alarm")
H.eq(W.sample(wd, 1, 410), "alarm", "alarm edge happens on a low sample")
H.eq(wd.alarm, true, "alarm latched")
H.eq(W.sample(wd, 5, 500), "none", "deadband keeps a latched alarm")
H.eq(wd.alarm, true, "alarm still latched")
H.eq(wd.state, "alarm", "state stayed alarm")
H.eq(W.sample(wd, 9, 900), "none", "9 is not high enough to clear")
H.eq(wd.alarm, true, "alarm survives a near-recovery")
H.eq(W.sample(wd, 10, 950), "clear", "only high clears")

-- Config validation ----------------------------------------------------------

H.group("watchdog-config")
local cfg, problems = W.sanitize({})
H.eq(#problems, 0, "empty options are clean")
H.num(cfg.low, 2, "sanitize fills low")
H.num(cfg.high, 10, "sanitize fills high")

cfg, problems = W.sanitize({ low = 9, high = 5 })
H.ok(#problems >= 1, "high <= low is reported", #problems)
H.num(cfg.low, 2, "high <= low resets low")
H.num(cfg.high, 10, "high <= low resets high")
H.contains(problems[1], "high=", "problem names the offending key")

cfg, problems = W.sanitize({ low = -1 })
H.ok(#problems >= 1, "negative low is reported")
H.contains(problems[1], "low", "problem mentions low")
H.num(cfg.low, 2, "negative low falls back")

cfg, problems = W.sanitize({ low = 16 })
H.ok(#problems >= 1, "low above 15 is reported")
H.num(cfg.low, 2, "low above 15 falls back")

cfg, problems = W.sanitize({ low = 2.5 })
H.ok(#problems >= 1, "non integer level is reported")
H.num(cfg.low, 2, "non integer level falls back")

cfg, problems = W.sanitize({ window = 0 })
H.ok(#problems >= 1, "zero window is reported")
H.num(cfg.window, 300, "zero window falls back")
cfg, problems = W.sanitize({ window = -5 })
H.ok(#problems >= 1, "negative window is reported")
cfg, problems = W.sanitize({ window = 99999999 })
H.ok(#problems >= 1, "absurd window is reported")

cfg, problems = W.sanitize({ poll = 0 })
H.ok(#problems >= 1, "zero poll is reported")
H.num(cfg.poll, 10, "zero poll falls back")
cfg, problems = W.sanitize({ poll = 0.5 })
H.eq(#problems, 0, "fractional poll is accepted")
H.num(cfg.poll, 0.5, "fractional poll kept")

cfg, problems = W.sanitize({ alarm_side = "nope" })
H.ok(#problems >= 1, "bad alarm side is reported")
H.eq(cfg.alarm_side, "left", "bad alarm side falls back")
cfg, problems = W.sanitize({ alarm_side = 7 })
H.ok(#problems >= 1, "non string alarm side is reported")
cfg, problems = W.sanitize({ input_side = "TOP" })
H.eq(#problems, 0, "side names are case insensitive")
H.eq(cfg.input_side, "top", "side name normalised")

cfg, problems = W.sanitize({ enabled = "false" })
H.eq(#problems, 0, "string false accepted")
H.eq(cfg.enabled, false, "String false disables")
cfg, problems = W.sanitize({ enabled = 0 })
H.eq(cfg.enabled, false, "numeric 0 disables")
cfg, problems = W.sanitize({ enabled = "sometimes" })
H.ok(#problems >= 1, "unparsable enabled reported")
H.eq(cfg.enabled, true, "unparsable enabled keeps the default")

local wf = newW({ enabled = false })
H.eq(wf.problem_count, 0, "disabled is a valid config")
H.eq(W.sample(wf, 1, 0), "disabled", "disabled sample reports disabled")
H.eq(wf.checks, 0, "disabled watchdog counts no samples")
H.eq(wf.state, "disabled", "state is disabled")
local ds, dtext = W.status(wf)
H.eq(ds.enabled, false, "status shows disabled")
H.contains(dtext, "enabled=0", "summary shows enabled=0")

local bad = newW({ low = 9, high = 5, window = 0, poll = -1 })
H.ok(bad.problem_count >= 3, "several problems collected together")
H.eq(bad.problem_count, #bad.problems, "problem_count matches the list")

-- Status text ----------------------------------------------------------------

H.group("watchdog-status")
local ws = newW({ low = 2, high = 10, window = 30, poll = 5,
    alarm_side = "right", input_side = "top" })
W.sample(ws, 1, 0)
W.sample(ws, 1, 30)
local ss, stext = W.status(ws)
H.eq(ss.state, "alarm", "status state alarm")
H.eq(ss.zone, "low", "status zone low")
H.eq(ss.alarm, true, "status alarm true")
H.eq(ss.alarm_side, "right", "status alarm side")
H.eq(ss.input_side, "top", "status input side")
H.num(ss.window, 30, "status window")
H.num(ss.poll, 5, "status poll")
H.num(ss.low_for, 30, "status low_for")
H.num(ss.checks, 2, "status checks")
H.num(ss.alarms, 1, "status alarms")
H.contains(stext, "state=alarm zone=low", "summary state and zone")
H.contains(stext, "alarm=1", "summary alarm flag")
H.contains(stext, "low_for=30", "summary low_for")
H.contains(stext, "checks=2", "summary checks")
H.contains(stext, "alarms=1 recoveries=0", "summary counters")
H.lacks(stext, "nil", "summary has no nil")
local nilStatus = W.status(nil)
H.isType(nilStatus, "table", "status tolerates nil state")
H.eq(nilStatus.state, "init", "nil state reports init")

-- Robustness -----------------------------------------------------------------

H.group("watchdog-robustness")
local wr = newW({})
H.eq(W.sample(wr, "abc", 0), "none", "non numeric level is ignored")
H.eq(wr.bad_samples, 1, "bad sample counted")
H.eq(wr.checks, 0, "bad sample does not advance the machine")
H.eq(wr.level, nil, "level untouched by a bad sample")
H.eq(W.sample(wr, 5, nil), "none", "missing time is ignored")
H.eq(wr.checks, 0, "missing time does not advance the machine")
H.eq(W.sample(wr, 5, 100), "none", "valid sample advances")
H.eq(wr.checks, 1, "one check")
H.eq(W.sample(wr, 5, 50), "none", "backwards clock is tolerated")
H.eq(wr.clock_skew, 1, "clock skew counted")
H.num(wr.last_now, 100, "clock is clamped, never moved backwards")
H.eq(W.sample(nil, 5, 100), "none", "nil state is tolerated")
local wstr = newW({ low = "3", high = "12", window = "60", poll = "15" })
H.num(wstr.cfg.low, 3, "numeric strings accepted for low")
H.num(wstr.cfg.high, 12, "numeric strings accepted for high")
H.num(wstr.cfg.window, 60, "numeric strings accepted for window")
H.num(wstr.cfg.poll, 15, "numeric strings accepted for poll")
local wunknown = newW({ nonsense = true })
H.eq(wunknown.problem_count, 0, "unknown options are ignored")
local shared = newW({})
shared.cfg.low = 0
H.num(W.DEFAULTS.low, 2, "instances do not mutate the defaults")
local wg = newW({ low = 0, high = 1, window = 1 })
H.eq(W.sample(wg, 0, 0), "none", "low=0 disables the low zone")
H.eq(wg.zone, "deadband", "level 0 with low=0 is deadband")
H.eq(W.sample(wg, 1, 0), "none", "high=1 sample is healthy")
H.eq(wg.zone, "healthy", "level 1 with high=1 is healthy")
H.eq(wg.state, "ok", "level 1 with high=1 is ok")

-- Switch / restore configuration ---------------------------------------------

H.group("watchdog-switch-config")
local wd = newW({})
H.num(wd.cfg.switch_to, 2, "default switch target is the backup battery")
H.eq(wd.cfg.restore, true, "restore is on by default")
local sdef = select(1, W.status(wd))
H.num(sdef.switch_to, 2, "status carries the switch target")
H.eq(sdef.restore, true, "status carries the restore flag")
H.contains(select(2, W.status(wd)), "switch_to=2 restore=1", "summary carries both")

local cfg = W.sanitize({ switch_to = 0 })
H.num(cfg.switch_to, 0, "switch_to 0 (disable) is accepted")
cfg = W.sanitize({ switch_to = "3" })
H.num(cfg.switch_to, 3, "switch_to accepts numeric strings")
local cfgHalf, problemsHalf = W.sanitize({ switch_to = 2.5 })
H.ok(#problemsHalf >= 1, "non integer switch_to is reported")
H.num(cfgHalf.switch_to, 2, "non integer switch_to falls back to the default")
local cfgBad, problemsBad = W.sanitize({ switch_to = 7 })
H.ok(#problemsBad >= 1, "switch_to above 3 is reported")
H.num(cfgBad.switch_to, 2, "switch_to above 3 falls back")
H.contains(problemsBad[1], "switch_to", "the problem names switch_to")

cfg = W.sanitize({ restore = "false" })
H.eq(cfg.restore, false, "restore accepts string false")
cfg = W.sanitize({ restore = 0 })
H.eq(cfg.restore, false, "restore accepts numeric 0")
local cfgRestoreBad, problemsRestore = W.sanitize({ restore = "sometimes" })
H.ok(#problemsRestore >= 1, "unparsable restore is reported")
H.eq(cfgRestoreBad.restore, true, "unparsable restore keeps the default")
H.contains(problemsRestore[1], "restore", "the problem names restore")

local woff = newW({ switch_to = 1, restore = false })
H.num(woff.cfg.switch_to, 1, "a custom switch target is kept")
H.eq(woff.cfg.restore, false, "restore=false is kept")
