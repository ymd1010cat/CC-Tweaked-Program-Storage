# pyroet-os/tools/smoke-run.ps1 -- P1 acceptance: run the rpv-subset smoke test.
#
#   pwsh -File pyroet-os\tools\smoke-run.ps1
#   pwsh -File pyroet-os\tools\smoke-run.ps1 -Keep       # keep the staging dir
#
# Stages a throw-away CraftOS-PC data directory at pyroet-os/.smoke:
#
#     .smoke/computer/20/system/rpv/*.lua  the ten vendored files (the image path)
#     .smoke/computer/20/smoke.lua   copied from pyroet-os/tools/smoke.lua
#     .smoke/computer/20/startup.lua generated here, runs smoke.lua
#
# then boots it headless with the CraftOS-PC console build, parses the SMOKE
# markers out of stdout, prints them, deletes the staging directory and exits
# 0 only when a SMOKE_PASS line was seen and no SMOKE_FAIL line was.
#
# Everything the script writes lives under pyroet-os/.smoke and is removed again,
# so a run leaves the work tree clean apart from the tracked sources.
param(
    [int]$TimeoutSec = 120,
    [string]$Exe = "C:\Program Files\CraftOS-PC\CraftOS-PC_console.exe",
    [switch]$Keep
)

$ErrorActionPreference = "Stop"

$here = Split-Path -Parent $MyInvocation.MyCommand.Path      # pyroet-os/tools
$osRoot = Split-Path -Parent $here                          # pyroet-os
$stage = Join-Path $osRoot ".smoke"
$comp = Join-Path $stage "computer\20"
$stdout = Join-Path $stage "stdout.txt"
$stderr = Join-Path $stage "stderr.txt"

if (-not (Test-Path $Exe)) {
    Write-Output "SMOKE_ERROR missing emulator: $Exe"
    exit 2
}
if (-not (Test-Path (Join-Path $osRoot "system\rpv\node.lua"))) {
    Write-Output "SMOKE_ERROR missing sources: pyroet-os/system/rpv/node.lua"
    exit 2
}

function Cleanup {
    if ($Keep) {
        Write-Output "SMOKE_STAGE kept at $stage"
        return
    }
    if (Test-Path $stage) { Remove-Item -Recurse -Force $stage -ErrorAction SilentlyContinue }
}

try {
    if (Test-Path $stage) { Remove-Item -Recurse -Force $stage }
    New-Item -ItemType Directory -Force -Path (Join-Path $comp "system\rpv") | Out-Null
    Copy-Item (Join-Path $osRoot "system\rpv\*.lua") (Join-Path $comp "system\rpv") -Force
    Copy-Item (Join-Path $osRoot "tools\smoke.lua") (Join-Path $comp "smoke.lua") -Force

    # minimal boot shim: CraftOS runs startup.lua at boot; the smoke script prints
    # the markers itself, so all this has to do is not swallow an error.
    $startup = @(
        "-- P1 smoke entry (generated by pyroet-os/tools/smoke-run.ps1).",
        "local ok, err = pcall(dofile, `"smoke.lua`")",
        "if not ok then",
        "    print(`"SMOKE_FAIL_AT startup `" .. tostring(err))",
        "    print(`"SMOKE_FAIL 1`")",
        "    print(`"SMOKE_DONE`")",
        "end"
    )
    Set-Content -Path (Join-Path $comp "startup.lua") -Value $startup -Encoding ascii

    $proc = Start-Process -FilePath $Exe -ArgumentList @("-d", "`"$stage`"", "--headless", "--id", "20") `
        -RedirectStandardOutput $stdout -RedirectStandardError $stderr -PassThru -NoNewWindow

    $deadline = (Get-Date).AddSeconds($TimeoutSec)
    $done = $false
    while ((Get-Date) -lt $deadline) {
        Start-Sleep -Milliseconds 300
        if ($proc.HasExited) { break }
        if (Test-Path $stdout) {
            $probe = Get-Content $stdout -Raw
            if ($probe -match "SMOKE_DONE") { $done = $true; break }
        }
    }
    Start-Sleep -Milliseconds 300
    if (-not $proc.HasExited) { $proc.Kill() }
    Start-Sleep -Milliseconds 200

    $text = if (Test-Path $stdout) { (Get-Content $stdout -Raw) -replace "`r", "" } else { "" }

    # CraftOS-PC redraws partial lines, so a fragment can appear several times:
    # match with regex over the whole text and de-duplicate instead of splitting.
    function Get-Uniq([string]$pattern) {
        @([regex]::Matches($text, $pattern) | ForEach-Object { $_.Value.Trim() } | Select-Object -Unique)
    }
    $passLine = (Get-Uniq "SMOKE_PASS \d+" | Select-Object -Last 1)
    $failLine = (Get-Uniq "SMOKE_FAIL \d+" | Select-Object -Last 1)
    $assertLine = (Get-Uniq "SMOKE_ASSERTS \d+ pass=\d+ fail=\d+" | Select-Object -Last 1)
    $groups = Get-Uniq "SMOKE_GROUP \w+"
    $details = Get-Uniq "SMOKE_FAIL_AT \S+"
    $subsetLogs = Get-Uniq "SMOKE_LOG RPV_SUBSET_\w+"
    $crashes = Get-Uniq "(SMOKE_ERROR|RPV_SUBSET|panic|attempt to call) [^\n]*"

    Write-Output "--- smoke output (de-duplicated markers) ---"
    foreach ($line in $groups) { Write-Output $line }
    foreach ($line in $details) { Write-Output $line }
    foreach ($line in $subsetLogs) { Write-Output $line }
    if ($assertLine) { Write-Output $assertLine }
    if ($passLine) { Write-Output $passLine }
    if ($failLine) { Write-Output $failLine }
    if (-not $done) { Write-Output "SMOKE_ERROR no SMOKE_DONE marker before timeout" }
    foreach ($line in $crashes) { if ($line -notmatch "^SMOKE_") { Write-Output $line } }
    Write-Output "--- end smoke output ---"

    if ($done -and $passLine -and -not $failLine) {
        Write-Output "SMOKE_RESULT PASS ($passLine)"
        Cleanup
        exit 0
    }
    if (-not $text) { Write-Output "SMOKE_ERROR emulator produced no stdout (check $stderr contents)" }
    Write-Output "SMOKE_RESULT FAIL"
    Cleanup
    exit 1
}
catch {
    Write-Output ("SMOKE_ERROR " + $_.Exception.Message)
    Cleanup
    exit 2
}
